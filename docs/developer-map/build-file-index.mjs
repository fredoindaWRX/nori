// Regenerates docs/developer-map/APP-FILES.md: every source file of the INSTALLED Nori app (app.asar) with the
// first comment line from the file itself, so the list cannot drift from what actually runs.
// Usage:  node C:\Nori\docs\developer-map\build-file-index.mjs [path\to\app.asar]
// Reads the archive only; changes nothing in it. Uses the npx-cached @electron/asar 4.3.1 (same one releases use).
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const ASAR_LIB = path.join(process.env.LOCALAPPDATA, 'npm-cache', '_npx', '4b0e2640fe917ac8', 'node_modules', '@electron', 'asar', 'lib', 'asar.js')
const archive = process.argv[2] || 'C:\\Program Files\\Nori\\resources\\app.asar'
const asar = await import(pathToFileURL(ASAR_LIB).href)
const hash = createHash('sha256').update(readFileSync(archive)).digest('hex').toUpperCase()
const SOURCE = /\.(mjs|cjs|js|py|ps1|html)$/

function firstComment(text) {
  const lines = text.split(/\r?\n/).slice(0, 40)
  const out = []
  let inBlock = false
  for (const raw of lines) {
    const line = raw.trim()
    if (!out.length && (line === '' || line.startsWith('#!') || line.startsWith("'use strict'") || line.startsWith('"use strict"'))) continue
    const opens = !inBlock && (line.startsWith('/*') || line.startsWith('"""'))
    if (inBlock || opens) {
      const body = opens ? line.slice(line.startsWith('/*') ? 2 : 3) : line
      const closes = /\*\/$|"""$/.test(body)
      const t = body.replace(/\*+\/$|"""$/g, '').replace(/^\*+/, '').trim()
      if (t) out.push(t)
      inBlock = !closes
      if (out.join(' ').length > 220 || closes) break
      continue
    }
    if (line.startsWith('//') || line.startsWith('#') || line.startsWith('<!--')) { const t = line.replace(/^\/\/+|^#+|^<!--|-->$/g, '').trim(); if (t) out.push(t); if (out.join(' ').length > 220) break; continue }
    break
  }
  const s = out.join(' ').replace(/\s+/g, ' ').trim()
  return s.length > 240 ? s.slice(0, 237) + '…' : s
}

const files = asar.listPackage(archive, { isPack: false })
  .map(f => f.replace(/^[\\/]/, '').replace(/\\/g, '/'))
  .filter(f => !f.startsWith('node_modules/') && SOURCE.test(f) && !/\.min\.js$/.test(f) && !f.startsWith('dist/assets/'))
  .sort()
const groups = new Map()
for (const f of files) {
  let text = ''
  try { text = asar.extractFile(archive, f).toString('utf8') } catch { continue }
  const dir = f.includes('/') ? f.slice(0, f.lastIndexOf('/')) : '(root)'
  if (!groups.has(dir)) groups.set(dir, [])
  const exported = [...text.matchAll(/^export\s+(?:async\s+)?(?:function\*?|const|class|let)\s+([A-Za-z_$][\w$]*)/gm)].map(m => m[1])
  const cjs = [...text.matchAll(/module\.exports\s*=\s*\{([^}]{0,300})\}/g)].flatMap(m => m[1].split(',').map(s => s.split(':')[0].trim()).filter(Boolean))
  const names = [...new Set([...exported, ...cjs])]
  const fallback = names.length ? `_(no header comment)_ exports: ${names.slice(0, 8).map(n => `\`${n}\``).join(', ')}${names.length > 8 ? ` +${names.length - 8} more` : ''}` : '_(no header comment: read the file)_'
  groups.get(dir).push(`| \`${f.slice(f.lastIndexOf('/') + 1)}\` | ${firstComment(text).replace(/\|/g, '\\|') || fallback} |`)
}
let md = `# Installed app files\n\nGenerated by \`build-file-index.mjs\` from \`${archive}\` (SHA-256 \`${hash.slice(0, 8)}…${hash.slice(-4)}\`) on ${new Date().toISOString().slice(0, 10)}.\nDo not edit by hand: re-run the script after every install. Descriptions are each file's own first comment.\n\n`
for (const [dir, rows] of groups) md += `## ${dir}/\n\n| File | What it says it does |\n|---|---|\n${rows.join('\n')}\n\n`
writeFileSync(new URL('./APP-FILES.md', import.meta.url), md)
console.log(`wrote APP-FILES.md: ${files.length} files in ${groups.size} folders from ${hash.slice(0, 8)}`)
