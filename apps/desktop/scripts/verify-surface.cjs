const { app, BrowserWindow } = require('electron')
const fs = require('node:fs')
const path = require('node:path')
app.whenReady().then(async () => {
  let server
  try {
    const { createServer } = await import('vite')
    server = await createServer({root:path.join(__dirname,'..'),server:{host:'127.0.0.1',port:5193,strictPort:true,watch:{ignored:['**/public/mediapipe/**','**/dist/**','**/artifacts/**']}}})
    await server.listen()
    const win=new BrowserWindow({width:1672,height:941,useContentSize:true,show:false,webPreferences:{offscreen:true,backgroundThrottling:false}})
    const errors=[]
    const providerWarnings=[]
    win.webContents.on('console-message',(_event,level,message)=>{if(level>=3){if(/terrain.reearth.land/.test(message))providerWarnings.push(message);else if(!/WebSocket|fetch|ERR_CONNECTION/.test(message))errors.push(message)}})
    await win.loadURL('http://127.0.0.1:5193/scripts/preview-surface.html')
    const out=path.join(__dirname,'..','artifacts','surface')
    fs.mkdirSync(out,{recursive:true})
    const delay=ms=>new Promise(r=>setTimeout(r,ms))
    const capture=async name=>{fs.writeFileSync(path.join(out,name+'.png'),(await win.webContents.capturePage()).toPNG());console.log('Captured',name)}
    await delay(3000)
    await capture('orbit')
    await win.webContents.executeJavaScript(`new Promise(resolve=>{let n=0;const t=setInterval(()=>{document.querySelector('canvas').dispatchEvent(new WheelEvent('wheel',{deltaY:-160,bubbles:true,cancelable:true}));if(++n===30){clearInterval(t);resolve()}},90)})`)
    await delay(6000)
    const street=await win.webContents.executeJavaScript(`document.querySelector('.earth-surface') ? ({...document.querySelector('.earth-surface').dataset}) : null`)
    if(!street)throw new Error('Scrolling toward the orb did not enter the Earth map.')
    console.log('Entered geographic map',JSON.stringify(street))
    if(Math.abs(Number(street.latitude)-Number(street.currentLatitude))>.001||Math.abs(Number(street.longitude)-Number(street.currentLongitude))>.001)throw new Error('The selected globe coordinate was not retained.')
    await delay(2500)
    await capture('arrival')
    await win.webContents.executeJavaScript(`document.querySelector('.earth-return').click()`)
    await delay(1700)
    if(await win.webContents.executeJavaScript(`Boolean(document.querySelector('.earth-surface'))`))throw new Error('Return to orbit did not exit surface mode.')
    await capture('returned-orbit')
    await win.webContents.executeJavaScript(`window.previewEarthAt({latitude:40.758,longitude:-73.9855})`)
    await delay(9000)
    await win.webContents.executeJavaScript(`new Promise(resolve=>{let n=0;const t=setInterval(()=>{document.querySelector('.earth-zoom-controls button').click();if(++n===6){clearInterval(t);resolve()}},500)})`)
    await delay(8000)
    await capture('real-time-night-lighting')
    await win.webContents.executeJavaScript(`document.querySelector('.earth-lighting').click()`)
    await delay(1000)
    await capture('real-satellite-buildings')
    const detail=await win.webContents.executeJavaScript(`({...document.querySelector('.earth-surface').dataset})`)
    if(detail.provider!=='esri'||Number(detail.height)>1000)throw new Error('High-detail satellite arrival failed: '+JSON.stringify(detail))
    console.log('Close Earth detail:',JSON.stringify(detail))
    await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='Flat map').click()`)
    await delay(3500)
    await capture('real-street-map')
    const loaded=await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('img.leaflet-tile-loaded')).filter(i=>i.naturalWidth>0).length`)
    if(loaded<4)throw new Error('Flat street map fallback did not load.')
    await win.webContents.executeJavaScript(`document.querySelector('.earth-back-to-globe').click()`)
    await delay(5000)
    const restored=await win.webContents.executeJavaScript(`({...document.querySelector('.earth-surface').dataset})`)
    if(Math.abs(Number(restored.currentLatitude)-Number(detail.currentLatitude))>.005||Math.abs(Number(restored.currentLongitude)-Number(detail.currentLongitude))>.005)throw new Error('Flat / 3D coordinate continuity failed.')
    if(providerWarnings.length) console.log('Terrain service returned',providerWarnings.length,'network/CORS warnings; recovery terrain:',restored.terrain)
    if(errors.length)throw new Error(errors.join('\n'))
    console.log('Verified: Cesium globe-to-map coordinates, real close satellite imagery, UTC/clear lighting, flat street-map fallback, coordinate-preserving 3D return, and return to orbit.')
  } catch(error){console.error(error);process.exitCode=1}
  finally{await server?.close();app.quit()}
})
