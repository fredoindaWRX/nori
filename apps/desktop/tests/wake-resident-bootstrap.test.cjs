const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const os=require('node:os')
const path=require('node:path')
const {residentProfile,qualificationOwnerPid,ownerProcessAlive}=require('../desktop/wake-resident-bootstrap.cjs')
test('resident profile selection requires prepared directory and creates nothing',t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'nori-wake-profile-'))
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}))
  assert.throws(()=>residentProfile(root))
  assert.equal(fs.existsSync(path.join(root,'wake')),false)
  fs.mkdirSync(path.join(root,'wake'))
  assert.equal(residentProfile(root),path.join(root,'wake'))
  fs.renameSync(path.join(root,'wake'),path.join(root,'real-wake'))
  fs.symlinkSync(path.join(root,'real-wake'),path.join(root,'wake'),'junction')
  assert.throws(()=>residentProfile(root),/redirected/)
})
test('qualification requires a distinct bounded owner pid',()=>{
  assert.equal(qualificationOwnerPid({NORI_WAKE_QUALIFICATION_OWNER_PID:'1234'}),1234)
  for(const value of [undefined,'','0','-1','1.5','abc','99999999999',String(process.pid)])
    assert.throws(()=>qualificationOwnerPid({NORI_WAKE_QUALIFICATION_OWNER_PID:value}))
})
test('qualification owner liveness is explicit and fail closed',()=>{
  assert.equal(ownerProcessAlive(42,(pid,signal)=>{assert.equal(pid,42);assert.equal(signal,0)}),true)
  assert.equal(ownerProcessAlive(42,()=>{throw Error('gone')}),false)
})
