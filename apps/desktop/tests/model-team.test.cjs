const test=require('node:test')
const assert=require('node:assert/strict')
const {importedModelProfile,desktopImportedModelProfile}=require('../desktop/imported-model-profile.cjs')
test('everyday profile is pinned and retains explicit 64K context',()=>{
  const model=importedModelProfile('qwen3.5-9b')
  assert.equal(model.defaultContext,65536)
  assert.equal(model.bytes,5627045248)
  assert.match(model.sha256,/^[a-f0-9]{64}$/)
  assert.equal(model.modelStoreRoot,'C:/Nori')
  assert.equal(model.verifyHashAtStartup,true)
  assert.equal(model.variant,'abliterated')
  assert.equal(model.revision,'419ca34f424adbd9276c09e0271cb6b718e8da1d')
  assert.equal(model.sha256,'ea1858ef4dc4b648b8dbb44612962a0333e945060dd0545ac0f28d7c4416e4b3')
  assert.match(model.relativePath,/huihui-qwen3\.5-9b-mradermacher-419ca34f\/Huihui-Qwen3\.5-9B-abliterated\.Q4_K_M\.gguf$/)
  assert.equal(desktopImportedModelProfile({packaged:true}).id,model.id)
  assert.equal(desktopImportedModelProfile({packaged:true,args:['--nori-qwen38']}).id,'qwen3.8-27b')
  assert.throws(()=>desktopImportedModelProfile({args:['--nori-qwen38','--nori-qwen35-9b']}),/only one/)
  assert.throws(()=>importedModelProfile('../../arbitrary'),/Unsupported/)
})
