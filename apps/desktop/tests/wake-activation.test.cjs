const test=require('node:test')
const assert=require('node:assert/strict')
const {createWakeActivation}=require('../desktop/wake-activation.cjs')
test('cold and second-instance requests deliver one explicit wake each',()=>{
  const wake=createWakeActivation(['Nori.exe','--nori-wake'])
  assert.equal(wake.consume(),true)
  assert.equal(wake.consume(),false)
  wake.request(['--other'])
  assert.equal(wake.consume(),false)
  wake.request(['--nori-wake']);wake.request(['--nori-wake'])
  assert.equal(wake.consume(),true)
  assert.equal(wake.consume(),false)
  wake.request(null)
  assert.equal(wake.consume(),false)
})
