const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const os=require('node:os')
const path=require('node:path')
const {inspectSelectedWakeApp}=require('../desktop/selected-wake-app.cjs')

test('selected wake target checks both executable and app archive and refuses corruption',async t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'nori-wake-target-'))
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}))
  const release=path.join(root,'apps/desktop/release')
  const base=path.join(release,'native-desktop-test')
  const output=path.join(base,'win-unpacked')
  fs.mkdirSync(path.join(output,'resources'),{recursive:true})
  fs.writeFileSync(path.join(output,'Nori.exe'),'synthetic exe')
  fs.writeFileSync(path.join(output,'resources/app.asar'),'synthetic archive')
  fs.writeFileSync(path.join(release,'current-desktop.txt'),'test\n')
  const {buildComponentManifest}=await import('../scripts/component-integrity.mjs')
  const receipt={schema:1,candidate:'test',desktopManifest:buildComponentManifest(output,['Nori.exe','resources/app.asar'])}
  const receiptPath=path.join(base,'native-desktop-receipt.json')
  fs.writeFileSync(receiptPath,JSON.stringify(receipt))
  const result=await inspectSelectedWakeApp(root)
  assert.equal(result.candidate,'test')
  assert.equal(result.integrity.verified_files,2)
  assert.equal(result.activationPerformed,false)
  fs.writeFileSync(path.join(output,'resources/app.asar'),'corrupt')
  await assert.rejects(inspectSelectedWakeApp(root),/integrity mismatch/)
  receipt.candidate='other'
  fs.writeFileSync(receiptPath,JSON.stringify(receipt))
  await assert.rejects(inspectSelectedWakeApp(root),/receipt mismatch/)
  fs.writeFileSync(path.join(release,'current-desktop.txt'),'../../other')
  await assert.rejects(inspectSelectedWakeApp(root),/candidate/)
})
